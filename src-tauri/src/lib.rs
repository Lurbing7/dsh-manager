/// Windows tracks the taskbar theme separately from the app theme
/// (`SystemUsesLightTheme`), and that is what the tray icon has to blend with.
#[cfg(windows)]
fn taskbar_is_light() -> bool {
    use winreg::enums::HKEY_CURRENT_USER;
    use winreg::RegKey;
    RegKey::predef(HKEY_CURRENT_USER)
        .open_subkey(r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize")
        .and_then(|k| k.get_value::<u32, _>("SystemUsesLightTheme"))
        .map(|v| v == 1)
        .unwrap_or(false)
}

#[cfg(not(windows))]
fn taskbar_is_light() -> bool {
    false
}

fn tray_image(running: bool, light: bool) -> tauri::image::Image<'static> {
    let bytes: &'static [u8] = match (running, light) {
        (false, false) => TRAY_OFF_DARK,
        (true, false) => TRAY_ON_DARK,
        (false, true) => TRAY_OFF_LIGHT,
        (true, true) => TRAY_ON_LIGHT,
    };
    tauri::image::Image::from_bytes(bytes).expect("embedded tray icon must decode")
}

/// Tray icon + tooltip together cover the two things worth glancing at:
/// whether the harness is up, and whether dsh can be updated.
fn refresh_tray(app: &AppHandle) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    let running = HARNESS_RUNNING.load(Ordering::Relaxed);
    let light = TASKBAR_LIGHT.load(Ordering::Relaxed);
    let _ = tray.set_icon(Some(tray_image(running, light)));

    let run_text = if running {
        "harness 运行中"
    } else {
        "harness 未启动"
    };
    let ver_text = match load_state(app) {
        Some(s) => match (&s.last_local_version, &s.last_latest_version) {
            (Some(local), Some(latest)) if is_newer(latest, Some(local)) => {
                format!("有新版本 {latest}")
            }
            (Some(local), _) => format!("dsh {local}"),
            _ => "dsh 版本未知".to_string(),
        },
        None => "尚未检查更新".to_string(),
    };
    let _ = tray.set_tooltip(Some(&format!("DSH Panel · {run_text} · {ver_text}")));
}

fn show_panel(app: &AppHandle) {
    if let Some(w) = app.get_webview_window("main") {
        let _ = w.show();
        let _ = w.unminimize();
        let _ = w.set_focus();
    }
}

