/// Aggregate the store into day / week / month buckets.
#[tauri::command]
fn usage_series(app: AppHandle, bucket: Option<String>, count: Option<u32>) -> UsageSeries {
    let bucket = bucket.unwrap_or_else(|| "day".into());
    let default_count = match bucket.as_str() {
        "week" => 8,
        "month" => 12,
        _ => 14,
    };
    let count = count.unwrap_or(default_count).clamp(1, 60);

    let fail = |err: String| UsageSeries {
        ok: false,
        bucket: bucket.clone(),
        points: Vec::new(),
        total_cost: 0.0,
        total_tokens: 0,
        total_calls: 0,
        month_cost: 0.0,
        month_tokens: 0,
        month_calls: 0,
        filled: 0,
        error: Some(err),
    };

    let days = match load_all_days(&app) {
        Ok(d) => d,
        Err(e) => return fail(e),
    };

    let today = chrono::Local::now().date_naive();
    let month_prefix = today.format("%Y-%m").to_string();

    // Current calendar month totals, always computed regardless of bucket.
    let mut month_cost = 0.0;
    let mut month_tokens = 0u64;
    let mut month_calls = 0u64;
    for d in &days {
        if d.date.starts_with(&month_prefix) {
            month_cost += d.total.cost;
            month_tokens += d.total.tokens();
            month_calls += d.total.calls;
        }
    }

    // Bucket key + label for one day, plus the ordered list of buckets we want.
    let key_of = |date: &chrono::NaiveDate| -> String {
        match bucket.as_str() {
            "week" => date.format("%G-W%V").to_string(),
            "month" => date.format("%Y-%m").to_string(),
            _ => date.format("%Y-%m-%d").to_string(),
        }
    };

    let mut wanted: Vec<String> = Vec::new();
    match bucket.as_str() {
        "week" => {
            // Count back whole weeks from the current ISO week.
            let mut cursor = today;
            for _ in 0..count {
                wanted.push(key_of(&cursor));
                cursor -= chrono::Duration::days(7);
            }
        }
        "month" => {
            let mut year = today.year();
            let mut month = today.month();
            for _ in 0..count {
                wanted.push(format!("{year:04}-{month:02}"));
                if month == 1 {
                    month = 12;
                    year -= 1;
                } else {
                    month -= 1;
                }
            }
        }
        _ => {
            let mut cursor = today;
            for _ in 0..count {
                wanted.push(cursor.format("%Y-%m-%d").to_string());
                cursor -= chrono::Duration::days(1);
            }
        }
    }
    wanted.reverse(); // oldest -> newest

    // Fold the store into those buckets.
    let mut acc: HashMap<String, (f64, u64, u64)> = HashMap::new();
    let horizon = wanted.first().cloned().unwrap_or_default();
    for d in &days {
        let key = d.date.clone();
        // Only keep days that can land in a wanted bucket.
        let in_range = match bucket.as_str() {
            "month" => key.as_str() >= horizon.as_str(),
            _ => true,
        };
        if !in_range {
            continue;
        }
        let bucket_key = match bucket.as_str() {
            "week" | "month" => match chrono::NaiveDate::parse_from_str(&key, "%Y-%m-%d") {
                Ok(date) => key_of(&date),
                Err(_) => continue,
            },
            _ => key,
        };
        if !wanted.contains(&bucket_key) {
            continue;
        }
        let slot = acc.entry(bucket_key).or_insert((0.0, 0, 0));
        slot.0 += d.total.cost;
        slot.1 += d.total.tokens();
        slot.2 += d.total.calls;
    }

    let mut points = Vec::new();
    let mut filled = 0u32;
    for key in &wanted {
        let (cost, tokens, calls) = acc.get(key).copied().unwrap_or((0.0, 0, 0));
        if calls > 0 {
            filled += 1;
        }
        let label = match bucket.as_str() {
            "week" => key
                .split("-W")
                .nth(1)
                .map(|w| format!("第{w}周"))
                .unwrap_or_else(|| key.clone()),
            "month" => key
                .split('-')
                .nth(1)
                .map(|m| format!("{m}月"))
                .unwrap_or_else(|| key.clone()),
            _ => key.get(5..).unwrap_or(key).to_string(),
        };
        points.push(UsagePoint {
            label,
            key: key.clone(),
            cost,
            tokens,
            calls,
        });
    }

    let total_cost = points.iter().map(|p| p.cost).sum();
    let total_tokens = points.iter().map(|p| p.tokens).sum();
    let total_calls = points.iter().map(|p| p.calls).sum();

    UsageSeries {
        ok: true,
        bucket,
        points,
        total_cost,
        total_tokens,
        total_calls,
        month_cost,
        month_tokens,
        month_calls,
        filled,
        error: None,
    }
}

/// Read one secret out of the harness credential store (`~/.dsh/.credentials.yaml`).
///
/// Only `refs.<NAME>` is needed, so this scans lines instead of pulling in a YAML
/// parser: it keeps unrelated secrets off the heap entirely, and the file is a
/// flat `refs:` block in every version we have seen.
fn read_dsh_credential(name: &str) -> Option<String> {
    let home = std::env::var("USERPROFILE").ok()?;
    let path = PathBuf::from(home).join(".dsh").join(".credentials.yaml");
    let text = std::fs::read_to_string(path).ok()?;

    let mut in_refs = false;
    let prefix = format!("{name}:");
    for line in text.lines() {
        if !in_refs {
            if line.trim_start().starts_with("refs:") && !line.starts_with(' ') {
                in_refs = true;
            }
            continue;
        }
        // A non-indented, non-empty line ends the refs block.
        if !line.trim().is_empty() && !line.starts_with(' ') && !line.starts_with('\t') {
            break;
        }
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix(&prefix) {
            let value = rest.trim().trim_matches(|c| c == '"' || c == '\'');
            if !value.is_empty() && !value.starts_with('<') {
                return Some(value.to_string());
            }
        }
    }
    None
}

/// Query the provider balance ourselves.
///
/// The plugin used to do this, but the whole point of the panel owning its own
/// data is that uninstalling plugins must not remove working features.
#[tauri::command]
async fn get_balance_native(provider: Option<String>) -> BalanceInfo {
    let provider = provider.unwrap_or_else(|| "deepseek".into());
    let fail = |err: String| BalanceInfo {
        ok: false,
        provider: provider.clone(),
        currency: String::new(),
        total: String::new(),
        topped_up: String::new(),
        granted: String::new(),
        queried_at: 0,
        error: Some(err),
    };

    let Some(key) = read_dsh_credential("DEEPSEEK_API_KEY") else {
        return fail("在 ~/.dsh/.credentials.yaml 的 refs 里找不到 DEEPSEEK_API_KEY".into());
    };

    let client = match reqwest::Client::builder()
        .timeout(Duration::from_secs(20))
        .build()
    {
        Ok(c) => c,
        Err(e) => return fail(format!("创建 HTTP 客户端失败: {e}")),
    };

    let resp = match client
        .get("https://api.deepseek.com/user/balance")
        .bearer_auth(&key)
        .header("Accept", "application/json")
        .send()
        .await
    {
        Ok(r) => r,
        Err(e) => return fail(format!("请求 DeepSeek 余额接口失败: {e}")),
    };

    if !resp.status().is_success() {
        let status = resp.status();
        return fail(match status.as_u16() {
            401 => "DeepSeek 返回 401：API Key 无效或已撤销".to_string(),
            402 => "DeepSeek 返回 402：账户余额不足".to_string(),
            _ => format!("DeepSeek 返回 HTTP {status}"),
        });
    }

    let value: serde_json::Value = match resp.json().await {
        Ok(v) => v,
        Err(e) => return fail(format!("解析余额响应失败: {e}")),
    };

    let info = &value["balance_infos"][0];
    let total = info["total_balance"].as_str().unwrap_or("").to_string();
    if total.is_empty() {
        return fail("余额响应里没有 total_balance".into());
    }

    BalanceInfo {
        ok: true,
        provider,
        currency: info["currency"].as_str().unwrap_or("CNY").to_string(),
        total,
        topped_up: info["topped_up_balance"].as_str().unwrap_or("").to_string(),
        granted: info["granted_balance"].as_str().unwrap_or("").to_string(),
        queried_at: now_secs(),
        error: None,
    }
}

// ---------------------------------------------------------------------------
// Session scanner
//
// The kernel (packages/llm/token-meter) derives exact per-turn token usage from
// session events, but never writes a separate usage file: the only durable
// record is the session log itself. Session logs are *multi-frame* zstd
// (one frame appended per write; the file we inspected held 1174 frames), so a
// single-shot decompressor fails on them - `zstd::stream::read::Decoder` walks
// frame boundaries itself.
// ---------------------------------------------------------------------------

fn sessions_root() -> Option<PathBuf> {
    let home = std::env::var("USERPROFILE").ok()?;
    let dir = PathBuf::from(home).join(".dsh").join("sessions");
    if dir.is_dir() {
        Some(dir)
    } else {
        None
    }
}

/// Every session log under the root (order unspecified; callers sort).
fn session_files(root: &PathBuf) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![root.clone()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path
                .file_name()
                .and_then(|n| n.to_str())
                .map(|n| n.ends_with(".jsonl.zstd"))
                .unwrap_or(false)
            {
                out.push(path);
            }
        }
    }
    out
}

/// Decompress a multi-frame zstd session log into its JSONL lines.
fn read_session_lines(path: &PathBuf) -> Result<Vec<String>, String> {
    use std::io::Read;
    let file = std::fs::File::open(path).map_err(|e| format!("打开失败: {e}"))?;
    let mut decoder =
        zstd::stream::read::Decoder::new(file).map_err(|e| format!("zstd 初始化失败: {e}"))?;
    let mut text = String::new();
    decoder
        .read_to_string(&mut text)
        .map_err(|e| format!("解压失败: {e}"))?;
    Ok(text.lines().map(|l| l.to_string()).collect())
}

/// Diagnostic pass: report what event types actually appear in the logs, so the
/// aggregation is written against the real structure rather than a guess.
#[tauri::command]
fn scan_sessions_diag(limit: Option<usize>) -> ActionResult {
    let Some(root) = sessions_root() else {
        return ActionResult {
            ok: false,
            action: "scan".into(),
            message: "找不到 ~/.dsh/sessions".into(),
            output: String::new(),
        };
    };
    let mut files = session_files(&root);
    files.sort();
    let limit = limit.unwrap_or(3);

    let mut by_type: HashMap<String, usize> = HashMap::new();
    let mut samples: Vec<String> = Vec::new();
    let mut usage_samples: Vec<String> = Vec::new();
    let mut events = 0usize;
    let mut total_lines = 0usize;
    let mut errors: Vec<String> = Vec::new();

    for path in files.iter().take(limit) {
        match read_session_lines(path) {
            Ok(lines) => {
                total_lines += lines.len();
                for line in lines {
                    let trimmed = line.trim();
                    if trimmed.is_empty() {
                        continue;
                    }
                    events += 1;
                    let Ok(v) = serde_json::from_str::<serde_json::Value>(trimmed) else {
                        continue;
                    };
                    let ty = v["type"].as_str().unwrap_or("<no type>").to_string();
                    *by_type.entry(ty.clone()).or_insert(0) += 1;

                    // Keep several raw usage objects: the first one may lack
                    // optional buckets, which hides the real accounting.
                    if ty == "assistant/message" && usage_samples.len() < 8 {
                        let usage = &v["data"]["usage"];
                        if !usage.is_null() {
                            usage_samples.push(format!(
                                "usage[{}] {}",
                                usage_samples.len(),
                                serde_json::to_string(usage).unwrap_or_default()
                            ));
                        } else {
                            usage_samples.push(format!(
                                "usage[{}] <null> keys={}",
                                usage_samples.len(),
                                v["data"]
                                    .as_object()
                                    .map(|o| o.keys().cloned().collect::<Vec<_>>().join(","))
                                    .unwrap_or_default()
                            ));
                        }
                    }
                    if ty.contains("turn/") && samples.len() < 2 {
                        samples.push(format!(
                            "[{ty}] {}",
                            trimmed.chars().take(300).collect::<String>()
                        ));
                    }
                }
            }
            Err(e) => errors.push(format!("{}: {e}", path.display())),
        }
    }

    let mut lines = vec![
        format!("扫描文件: {} / {}", limit.min(files.len()), files.len()),
        format!("事件行数: {total_lines}，解析成功 {events}"),
        String::new(),
        "事件类型分布:".to_string(),
    ];
    let mut types: Vec<_> = by_type.iter().collect();
    types.sort_by(|a, b| b.1.cmp(a.1));
    for (k, v) in types.iter().take(24) {
        lines.push(format!("  {k}: {v}"));
    }
    if !errors.is_empty() {
        lines.push(String::new());
        lines.push("错误:".into());
        for e in errors.iter().take(5) {
            lines.push(format!("  {e}"));
        }
    }
    lines.push(String::new());
    lines.push("assistant/message 的 usage 采样:".into());
    for s in &usage_samples {
        lines.push(format!("  {s}"));
    }
    lines.push(String::new());
    lines.push("turn 事件样本:".into());
    for s in &samples {
        lines.push(format!("  {s}"));
    }

    ActionResult {
        ok: true,
        action: "scan".into(),
        message: lines.join("\n"),
        output: String::new(),
    }
}

