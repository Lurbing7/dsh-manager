/// Start the harness *inside* the panel: its output is piped to the UI instead of
/// the harness opening in a separate console window.
#[tauri::command]
async fn start_harness_inline(app: AppHandle, port: Option<u16>) -> ActionResult {
    let port = port.unwrap_or(DEFAULT_HARNESS_PORT);
    let url = harness_url(port);

    if port_alive(&url).await {
        let _ = Command::new("cmd")
            .args(["/c", "start", "", &url])
            .creation_flags(CREATE_NO_WINDOW)
            .spawn();
        let msg = format!("harness 已在运行，已打开浏览器 {url}");
        let _ = app.emit("harness-output", msg.clone());
        return ActionResult {
            ok: true,
            action: "browser".into(),
            message: msg,
            output: String::new(),
        };
    }

    let mut child = match Command::new("cmd")
        .args(["/c", "dsh", "web", "--port", &port.to_string()])
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .creation_flags(CREATE_NO_WINDOW)
        .spawn()
    {
        Ok(c) => c,
        Err(e) => {
            return ActionResult {
                ok: false,
                action: "inline".into(),
                message: format!("启动失败: {e}"),
                output: String::new(),
            }
        }
    };

    let _ = app.emit("harness-output", format!("$ dsh web --port {port}"));

    if let Some(out) = child.stdout.take() {
        let handle = app.clone();
        std::thread::spawn(move || {
            for line in BufReader::new(out).lines().map_while(Result::ok) {
                let _ = handle.emit("harness-output", line);
            }
        });
    }
    if let Some(err) = child.stderr.take() {
        let handle = app.clone();
        std::thread::spawn(move || {
            for line in BufReader::new(err).lines().map_while(Result::ok) {
                let _ = handle.emit("harness-output", line);
            }
        });
    }

    *HARNESS_CHILD.get_or_init(|| Mutex::new(None)).lock().unwrap() = Some(child);

    ActionResult {
        ok: true,
        action: "inline".into(),
        message: format!("已在面板内启动 dsh web --port {port}，输出见下方终端"),
        output: String::new(),
    }
}

/// PIDs LISTENING on a TCP port, via Windows `netstat -ano`.
fn pids_on_port(port: u16) -> Vec<u32> {
    let Ok(out) = Command::new("cmd")
        .args(["/c", "netstat", "-ano", "-p", "tcp"])
        .creation_flags(CREATE_NO_WINDOW)
        .output()
    else {
        return Vec::new();
    };
    let text = String::from_utf8_lossy(&out.stdout);
    let suffix = format!(":{port}");
    let mut pids: Vec<u32> = Vec::new();
    for line in text.lines() {
        if !line.contains("LISTENING") {
            continue;
        }
        let cols: Vec<&str> = line.split_whitespace().collect();
        if cols.len() < 5 || !cols[1].ends_with(&suffix) {
            continue;
        }
        if let Ok(pid) = cols[4].parse::<u32>() {
            if !pids.contains(&pid) {
                pids.push(pid);
            }
        }
    }
    pids
}

/// Image name for a PID. Used so we never kill something unrelated that merely
/// happens to hold the port.
fn process_name(pid: u32) -> Option<String> {
    let out = Command::new("cmd")
        .args([
            "/c",
            "tasklist",
            "/FI",
            &format!("PID eq {pid}"),
            "/FO",
            "CSV",
            "/NH",
        ])
        .creation_flags(CREATE_NO_WINDOW)
        .output()
        .ok()?;
    let text = String::from_utf8_lossy(&out.stdout);
    let first = text.lines().next()?.trim().to_string();
    if first.is_empty() || first.starts_with("INFO:") {
        return None;
    }
    first.split(',').next().map(|s| s.trim_matches('"').to_string())
}

/// Stop the harness. Prefers the child the panel launched; otherwise stops
/// whatever node process is listening on the port (that is how a harness started
/// elsewhere - a terminal, another tool - gets stopped from here).
#[tauri::command]
fn stop_harness(port: Option<u16>) -> ActionResult {
    let port = port.unwrap_or(DEFAULT_HARNESS_PORT);

    // 1) A harness the panel launched: kill our own subtree (panel -> cmd -> node).
    //    /T is safe here because those processes sit below us.
    if let Some(mut child) = HARNESS_CHILD
        .get_or_init(|| Mutex::new(None))
        .lock()
        .unwrap()
        .take()
    {
        let pid = child.id();
        let _ = Command::new("cmd")
            .args(["/c", "taskkill", "/PID", &pid.to_string(), "/F", "/T"])
            .creation_flags(CREATE_NO_WINDOW)
            .output();
        let _ = child.wait();
        return ActionResult {
            ok: true,
            action: "stop".into(),
            message: "已停止面板启动的 Web 端".into(),
            output: String::new(),
        };
    }

    // 2) A harness started elsewhere.
    //
    //    NEVER pass /T here. When the harness is what launched this panel (the
    //    panel then sits below it in the process tree) /T would kill the panel
    //    along with the target - the stop button would take the panel down too.
    let pids = pids_on_port(port);
    if pids.is_empty() {
        return ActionResult {
            ok: false,
            action: "stop".into(),
            message: format!("端口 {port} 上没有在监听的进程"),
            output: String::new(),
        };
    }

    let me = std::process::id();
    let mut killed: Vec<u32> = Vec::new();
    let mut refused: Vec<u32> = Vec::new();
    for pid in pids {
        if pid == me {
            refused.push(pid);
            continue;
        }
        let is_node = process_name(pid)
            .map(|n| n.eq_ignore_ascii_case("node.exe"))
            .unwrap_or(false);
        if !is_node {
            refused.push(pid);
            continue;
        }
        let ok = Command::new("cmd")
            .args(["/c", "taskkill", "/PID", &pid.to_string(), "/F"])
            .creation_flags(CREATE_NO_WINDOW)
            .output()
            .map(|o| o.status.success())
            .unwrap_or(false);
        if ok {
            killed.push(pid);
        } else {
            refused.push(pid);
        }
    }

    let join = |v: &[u32]| v.iter().map(|p| p.to_string()).collect::<Vec<_>>().join(", ");
    ActionResult {
        ok: !killed.is_empty(),
        action: "stop".into(),
        message: if !killed.is_empty() {
            format!("已停止占用端口 {port} 的 harness（PID {}）", join(&killed))
        } else {
            format!("端口 {port} 被非 node 进程占用（PID {}），没有动它", join(&refused))
        },
        output: String::new(),
    }
}

